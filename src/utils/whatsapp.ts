export const LAWYER_NAME = 'أ. عمرو طنطاوي';
export const LAW_FIRM_NAME = 'مكتب أ. عمرو طنطاوي للمحاماة والاستشارات القانونية';
export const FIRM_WHATSAPP_NUMBER = '201003676300';
export const FIRM_DISPLAY_PHONE = '01003676300';

export function cleanPhoneNumber(phone: string): string {
  let cleaned = phone.replace(/[^\d+]/g, '');
  if (cleaned.startsWith('01') && cleaned.length === 11) {
    cleaned = '2' + cleaned;
  }
  cleaned = cleaned.replace(/^\+/, '');
  return cleaned;
}

export function createWhatsAppUrl(phone: string, message: string): string {
  const cleaned = cleanPhoneNumber(phone);
  const encoded = encodeURIComponent(message);
  return `https://wa.me/${cleaned}?text=${encoded}`;
}

export function openWhatsApp(phone: string, message: string): void {
  const url = createWhatsAppUrl(phone, message);
  window.open(url, '_blank', 'noopener,noreferrer');
}

